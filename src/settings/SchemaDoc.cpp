QString latin(std::string_view text)
{
    return QString::fromLatin1(text.data(), static_cast<qsizetype>(text.size()));
}

QString escapeCell(QString text)
{
    return text.replace(u'|', QStringLiteral("\\|")).replace(u'\n', u' ');
}

QString allowedValues(const Definition& def)
{
    if (def.type == Type::Enum) {
        QStringList values;
        for (const Option& option : def.options) {
            values.append(u'`' + latin(option.id) + u'`');
        }
        return values.join(QStringLiteral(", "));
    }
    if (def.bounded()) {
        return QStringLiteral("%1 … %2").arg(def.min).arg(def.max);
    }
    return QStringLiteral("—");
}

QString displayValue(const Definition& def, const QVariant& value)
{
    QString text = formatTomlValue(def, value);
    if (def.type == Type::Url || def.type == Type::String || def.type == Type::StringList) {
        text = log::redactUrlCredentials(text);
    }
    return text;
}

