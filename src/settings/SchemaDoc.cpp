QString schemaMarkdown(const Schema& schema)
{
    QString out;
    out += QStringLiteral(
        "# Configuration reference\n\n"
        "<!-- Generated by `xmake docs-config` from src/settings/BuiltinSchema.cpp. Do not edit by hand. -->\n\n"
        "The configuration file is `~/.config/noctara/config.toml` (XDG_CONFIG_HOME is honoured). "
        "A documented template is written on first run, and edits are applied live.\n\n"
        "Precedence, lowest first: built-in defaults, system config (`/etc/xdg/noctara/config.toml`), "
        "user config, `NOCTARA_*` environment variables, command-line flags "
        "(`--set key=value` or the listed aliases). "
        "Settings marked *restart* take effect on the next launch.\n\n"
        "Secrets such as OAuth tokens and proxy credentials are never read from or written to this file; "
        "they live in the system secret store.\n");

    for (int c = 0; c < kCategoryCount; ++c) {
        const auto category = static_cast<Category>(c);
        bool header = false;
        for (const Section& section : schema.sections()) {
            if (section.category != category) {
                continue;
            }
            if (!header) {
                out += QStringLiteral("\n## %1\n").arg(QString::fromUtf8(categoryLabel(category)));
                header = true;
            }
            out += QStringLiteral("\n### `[%1]` %2\n\n%3\n\n")
                       .arg(latin(section.id), QString::fromUtf8(section.label), QString::fromUtf8(section.description));
            out += QStringLiteral("| Key | Type | Default | Allowed | Description |\n|---|---|---|---|---|\n");
            for (const Definition& def : schema.definitions()) {
                if (def.sectionId() != section.id) {
                    continue;
                }
                QStringList notes;
                if (def.requiresRestart()) {
                    notes.append(QStringLiteral("*restart*"));
                }
                if (def.advanced()) {
                    notes.append(QStringLiteral("*advanced*"));
                }
                notes.append(QStringLiteral("env `%1`").arg(Schema::environmentVariable(def)));
                if (!def.cliAlias.empty()) {
                    notes.append(QStringLiteral("CLI `--%1=`").arg(latin(def.cliAlias)));
                }
                out += QStringLiteral("| `%1` | %2 | `%3` | %4 | **%5.** %6 (%7) |\n")
                           .arg(latin(def.leafName()), latin(typeName(def.type)),
                                escapeCell(formatTomlValue(def, def.defaultValue)), escapeCell(allowedValues(def)),
                                escapeCell(QString::fromUtf8(def.label)), escapeCell(QString::fromUtf8(def.description)),
                                notes.join(QStringLiteral(", ")));
            }
        }
    }
    return out;
}

QString effectiveConfigReport(const SettingsStore& store)
{
    const Schema& schema = store.schema();
    QString out;
    QString currentSection;
    for (std::size_t i = 0; i < schema.size(); ++i) {
        const Definition& def = schema.at(i);
        const QString section = latin(def.sectionId());
        if (section != currentSection) {
            out += QStringLiteral("%1[%2]\n").arg(currentSection.isEmpty() ? QString() : QStringLiteral("\n"), section);
            currentSection = section;
        }
        out += QStringLiteral("%1 = %2  # %3\n")
                   .arg(latin(def.leafName()), displayValue(def, store.value(i)),
                        latin(layerName(store.effectiveLayer(i))));
    }
    return out;
}

